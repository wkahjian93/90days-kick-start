// Builds server/Code.gs from the shared files, so the Google server and the app always use the same rules.
// Run: node build.js   (then paste server/Code.gs into Apps Script and deploy a new version)
const fs = require('fs'), path = require('path');
const strip = s => s.replace(/\nif \(typeof module[^\n]*\n?/g, '\n');
const parts = ['docs/syllabus.js', 'docs/logic.js', 'docs/core.js', 'server/gas.js']
  .map(f => '/* ===== ' + f + ' ===== */\n' + strip(fs.readFileSync(path.join(__dirname, f), 'utf8')));
const out = '/* 90Days Kick Start server. Generated by build.js; edit the source files, not this one. */\n\n' + parts.join('\n');
fs.writeFileSync(path.join(__dirname, 'server/Code.gs'), out);
console.log('server/Code.gs written, ' + out.length + ' characters');
